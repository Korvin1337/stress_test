use axum::{
    Json, Router,
    extract::{Query, State},
    routing::{get, post},
    http::StatusCode, // Needed for status codes
};
use serde::{Deserialize, Serialize};
use sqlx::postgres::PgPoolOptions;

#[tokio::main]
async fn main() {
    // 1. Setup Database Connection Pool
    let pool = PgPoolOptions::new()
        .max_connections(50)
        // 👇 UPDATED: Connects to 'BenchmarkDatabase' as user 'postgres'
        .connect("postgres://postgres:pass@localhost/BenchmarkDatabase")
        .await
        .expect("Failed to connect to DB");

    // 2. Build Router
    let app = Router::new()
        .route("/api/products", get(list_products).post(create_product))
        .with_state(pool);

    // 3. Run Server
    let listener = tokio::net::TcpListener::bind("0.0.0.0:3000").await.unwrap();
    println!("🦀 Rust Axum running on port 3000");
    axum::serve(listener, app).await.unwrap();
}

// --- MODELS ---

#[derive(Serialize, sqlx::FromRow)]
struct Product {
    id: i32,
    name: String,
    price: f64,
}

// MISSING PART 1: The Input DTO
#[derive(Deserialize)]
struct CreateProductDto {
    name: String,
    price: f64,
}

// MISSING PART 2: Pagination Struct
#[derive(Deserialize)]
struct Pagination {
    #[serde(default = "default_page")]
    page: i32,
    #[serde(default = "default_size")]
    size: i32,
}
fn default_page() -> i32 { 1 }
fn default_size() -> i32 { 20 }

// --- HANDLERS ---

async fn list_products(
    State(pool): State<sqlx::PgPool>,
    Query(params): Query<Pagination>,
) -> Json<Vec<Product>> {
    let offset = (params.page - 1) * params.size;

    // SQLx macro checks query at compile time if you set valid DATABASE_URL
    let products = sqlx::query_as::<_, Product>("SELECT * FROM products LIMIT $1 OFFSET $2")
        .bind(params.size)
        .bind(offset)
        .fetch_all(&pool)
        .await
        .unwrap(); // In production use proper error handling

    Json(products)
}

// MISSING PART 3: The Create Handler
async fn create_product(
    State(pool): State<sqlx::PgPool>,
    Json(payload): Json<CreateProductDto>,
) -> (StatusCode, Json<Product>) {
    let product = sqlx::query_as::<_, Product>(
        "INSERT INTO products (name, price) VALUES ($1, $2) RETURNING id, name, price"
    )
    .bind(payload.name)
    .bind(payload.price)
    .fetch_one(&pool)
    .await
    .unwrap();

    (StatusCode::CREATED, Json(product))
}

