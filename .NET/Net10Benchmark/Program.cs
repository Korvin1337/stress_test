using Microsoft.EntityFrameworkCore;
using Data.Context;
using Business.Models;

var builder = WebApplication.CreateBuilder(args);

// 2025 Optimization: Use connection pooling and slim context
builder.Services.AddDbContextPool<AppDbContext>(opt =>
    opt.UseNpgsql(builder.Configuration.GetConnectionString("DefaultConnection")));

var app = builder.Build();

var api = app.MapGroup("/api/products");

// GET All (Pagination)
api.MapGet("/", async (AppDbContext db, int page = 1, int size = 20) =>
    await db.Products.AsNoTracking() // Performance: No tracking for read-only
        .OrderBy(p => p.Id)
        .Skip((page - 1) * size)
        .Take(size)
        .ToListAsync());

// POST
api.MapPost("/", async (Product p, AppDbContext db) => {
    db.Products.Add(p);
    await db.SaveChangesAsync();
    return Results.Created($"/api/products/{p.Id}", p);
});

// GET Single
api.MapGet("/{id}", async (int id, AppDbContext db) =>
    await db.Products.FindAsync(id) is Product p ? Results.Ok(p) : Results.NotFound());

app.Run();

